import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createHash } from 'node:crypto'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const directory = resolve(root, 'database/migrations')
const version = JSON.parse(readFileSync(resolve(root, 'package.json'), 'utf8')).version
const output = resolve(root, 'database/setup.sql')
// Northflank adapter DDL is applied separately from the numbered migration history.
const current = readdirSync(directory).filter(name => name.endsWith('.sql') && name !== 'northflank-postgres.sql').map(name => {
  const number = name === 'schema.sql' ? 1 : Number(name.match(/^schema-v(\d+)(?:-[a-z0-9-]+)?\.sql$/)?.[1])
  if (!Number.isInteger(number) || number < 1) throw new Error(`Unrecognized migration: ${name}`)
  return { name, number, source: readFileSync(resolve(directory, name), 'utf8') }
})
// Older source migrations were pruned from this repository. Preserve their compiled
// SQL and original checksums from the committed setup instead of dropping history.
const archived = [...readFileSync(output, 'utf8').matchAll(/^-- Included source: migrations\/(schema(?:-v\d+[^\n/]*)?\.sql)\n-- SHA-256: ([a-f\d]{64})\n([\s\S]*?)(?=\n\n-- Included source: |\n\n-- Fresh BXI-Core)/gm)]
  .filter(match => !current.some(file => file.name === match[1]))
  .map(match => ({ name: match[1], number: match[1] === 'schema.sql' ? 1 : Number(match[1].match(/^schema-v(\d+)/)[1]), source: match[3], hash: match[2] }))
const files = [...archived, ...current].sort((a, b) => a.number - b.number)
files.forEach((file, index) => { if (file.number !== index + 1) throw new Error('Migration versions must be consecutive and unique, beginning with schema.sql.') })
if (!files.length) throw new Error('No migrations found.')
const tables = [...new Set(files.flatMap(file => [...file.source.matchAll(/create table if not exists public\.([a-z_]+)/gi)].map(match => match[1])))].sort()
const tableArray = `array[${tables.map(name => `'${name}'`).join(',')}]`
const modules = '["action","clients","projects","inbox","items","documents","requirements","reports","ai","settings"]'
const sections = files.map(file => {
  const { name, source } = file
  // Only remove standalone SQL transaction statements, never PL/pgSQL BEGIN blocks.
  const body = source.replace(/^(?:begin;|commit;|notify pgrst, 'reload schema';)\s*$/gmi, '').trim()
  const hash = 'hash' in file ? file.hash : createHash('sha256').update(source).digest('hex')
  return `-- Included source: migrations/${name}\n-- SHA-256: ${hash}\n${body}`
})
const sql = `-- BA Client Ops Tracker v${version}: ONE-RUN FRESH DATABASE SETUP
-- Includes schema versions 1 through ${files.length}. Run this ENTIRE file once in Supabase SQL Editor.
-- Requires a NEW Supabase database with no existing BA Tracker tables.
-- Existing deployment / restored backup: DO NOT run this file. See database/README.md.
-- This creates schema and initial accounts, not a copy of your current data.
-- No default passwords: configure INTERNAL_ADMIN_BOOTSTRAP_PASSWORD and
-- BXI_CORE_BOOTSTRAP_PASSWORD on the app server (at least 12 characters each).
-- Generated by npm run db:bundle. Keep migration history; do not hand-edit this file.

begin;
select pg_advisory_xact_lock(hashtext('ba_client_ops_fresh_setup'));

do $setup_guard$
declare
  object_name text;
begin
  foreach object_name in array array['anon','authenticated','service_role'] loop
    if not exists (select 1 from pg_roles where rolname = object_name) then
      raise exception 'Supabase role % is missing. Use a new Supabase project for this setup.', object_name;
    end if;
  end loop;
  foreach object_name in array ${tableArray} loop
    if to_regclass(format('public.%I', object_name)) is not null then
      raise exception 'Fresh setup stopped: public.% already exists. No changes were applied. Use newer migrations for an existing installation; do not replay old migrations.', object_name;
    end if;
  end loop;
end;
$setup_guard$;

${sections.join('\n\n')}

-- Fresh BXI-Core starts with the current module list, including Requirements & Traceability.
update public.organizations set enabled_modules = '${modules}'::jsonb
where id = '00000000-0000-0000-0000-000000000001';
update public.app_users set modules = '${modules}'::jsonb,
  raw_data = jsonb_set(raw_data, '{modules}', '${modules}'::jsonb)
where id = 'admin' and organization_id = '00000000-0000-0000-0000-000000000001';

-- Apply explicit server-only grants even when the project's default grants differ.
grant usage on schema public to service_role;
do $setup_grants$
declare
  object_name text;
begin
  foreach object_name in array ${tableArray} loop
    execute format('alter table public.%I enable row level security', object_name);
    execute format('revoke all on table public.%I from public, anon, authenticated', object_name);
    execute format('grant all on table public.%I to service_role', object_name);
  end loop;
end;
$setup_grants$;

notify pgrst, 'reload schema';
commit;
select 'BA Client Ops Tracker database setup complete' as result, ${files.length} as schema_version;
`
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== sql) throw new Error('database/setup.sql is out of date. Run npm run db:bundle.')
  console.log(`Database setup matches ${files.length} migrations (${tables.length} tables).`)
} else {
  writeFileSync(output, sql)
  console.log(`Wrote database/setup.sql: ${files.length} migrations, ${tables.length} tables, one transaction.`)
}
